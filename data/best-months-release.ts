const released = new Set(Object.values(BEST_MONTHS_RELEASES).flat())

export const isBestMonthsReleased = (slug: string) => released.has(slug)

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

// Compact label for cards, e.g. [11, 12, 1, 2] -> "Nov - Feb", [3, 4, 9, 10] -> "Mar - Apr, Sep - Oct"
export function formatMonths(months: number[]): string {
  const set = new Set(months)
  if (set.size === 12) return "Year-round"
  // Start each run at a month whose predecessor is not included, so Nov-Feb stays one run
  const runs: string[] = []
  for (let m = 1; m <= 12; m++) {
    const prev = m === 1 ? 12 : m - 1
    if (!set.has(m) || set.has(prev)) continue
    let end = m
    while (set.has(end === 12 ? 1 : end + 1)) end = end === 12 ? 1 : end + 1
    runs.push(end === m ? MONTHS[m - 1] : `${MONTHS[m - 1]} - ${MONTHS[end - 1]}`)
  }
  return runs.join(", ")
}
